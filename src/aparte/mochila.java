public class mochila {
    int peso;
    int color;

    public mochila(int peso, int color) {
        this.peso = peso;
        this.color = color;
    }

    @Override
    public String toString() {
        return "mochila{" + "peso=" + peso + ", color=" + color + '}';
    }
    
    
}
